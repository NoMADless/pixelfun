import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Checker } from "../assert";
import {
  deployFresh,
  distinctSlotIds,
  fundPainter,
  type ChainContext,
} from "../chain";
import { CONFIG } from "../config";

const BATCHES = [1, 25, 50, 100] as const;
export const GAS_THRESHOLD = 3_000_000n;

export interface GasRow {
  pixels: number;
  gasUsed: bigint;
  boardAction: string;
}

export async function runGasScenario(
  chain: ChainContext,
  artifacts: Parameters<typeof deployFresh>[1],
  check: Checker,
  decimals: number,
  writeReport: boolean,
): Promise<GasRow[]> {
  check.section(`paint gas, full board (${decimals} decimals)`);
  const deployment = await deployFresh(chain, artifacts, decimals);
  const { vault } = deployment;

  // Fill all 66 board slots at the admission minimum.
  const boardPainters = chain.wallets.slice(5, 71);
  for (const wallet of boardPainters) {
    await fundPainter(deployment, wallet, CONFIG.minPixels);
    await vault.paint(
      wallet,
      Array.from({ length: CONFIG.minPixels }, (_, i) => i),
      Array.from({ length: CONFIG.minPixels }, () => 1),
    );
  }
  const board = await vault.getBoard(await vault.currentEpoch());
  check.equal("gas setup: full board", board.painters.length, 66);

  const rows: GasRow[] = [];
  for (let index = 0; index < BATCHES.length; index++) {
    const pixels = BATCHES[index];
    const wallet = chain.wallets[71 + index];
    await fundPainter(deployment, wallet, pixels);
    const ids = distinctSlotIds(pixels, 400 + index * 400);
    const colors = ids.map((_, i) => (i + index) % 32);
    const receipt = await vault.paint(wallet, ids, colors);
    const boardAction =
      pixels < CONFIG.minPixels
        ? "below MIN_PIXELS, no board write"
        : "newcomer, displaces minimum + rescans";
    rows.push({ pixels, gasUsed: receipt.gasUsed, boardAction });
    console.log(
      `  gas ${pixels.toString().padStart(3)} px: ${receipt.gasUsed.toString().padStart(8)} (${(
        Number(receipt.gasUsed) / pixels
      ).toFixed(0)} per px)`,
    );
    check.check(`paint ${pixels} px succeeds`, receipt.status === "success", `${receipt.gasUsed} gas`);
    check.check(
      `paint ${pixels} px stays under a 30M block`,
      receipt.gasUsed < 30_000_000n,
      `${receipt.gasUsed} gas`,
    );
  }

  // The measured 100-pixel cost drives the UI batch policy.
  const hundred = rows.find((row) => row.pixels === 100)?.gasUsed ?? 0n;
  const defaultBatch = hundred > GAS_THRESHOLD ? 50 : 100;
  console.log(
    `  100 px = ${hundred.toString()} gas -> UI batch cap ${defaultBatch} (budget ${GAS_THRESHOLD.toString()})`,
  );

  if (writeReport) {
    const lines = [
      "# Paint gas",
      "",
      "Generated by `npm run e2e:local` against the real `PixelFun` artifact on a local",
      "Anvil chain (chain id 31337, solc 0.8.26, optimizer 200). Gas is measured with",
      "`receipt.gasUsed`, not an estimate.",
      "",
      "Conditions: the top-66 board is full (66 entries at the 20-pixel minimum) and each",
      "measured paint uses a fresh painter, so the 25/50/100-pixel transactions include a",
      "board displacement and the `_findMin` rescan. Pixel ids are in distinct storage slots",
      "(`id = 32 × k`), the worst case for the packed canvas.",
      "",
      "| pixels | gas used | gas / pixel | board action |",
      "| ---: | ---: | ---: | --- |",
      ...rows.map(
        (row) =>
          `| ${row.pixels} | ${row.gasUsed.toString()} | ${(
            Number(row.gasUsed) / row.pixels
          ).toFixed(0)} | ${row.boardAction} |`,
      ),
      "",
      `100 pixels costs ${hundred.toString()} gas, which is ${
        hundred <= GAS_THRESHOLD ? "at or below" : "above"
      } the ~3,000,000 UI budget.`,
      `The UI therefore splits drafts at ${defaultBatch} pixels per transaction${
        defaultBatch === 100 ? " (the contract maximum)" : ", with an advanced option up to 100"
      }.`,
      "",
      "The UI estimates each batch with `eth_estimateGas`, adds a 20% buffer and sends an",
      "explicit `gas` limit, so a full-board paint does not fail on a stale default limit.",
      "",
    ];
    writeFileSync(join(process.cwd(), "GAS.md"), lines.join("\n"), "utf8");
    console.log(`  wrote GAS.md (UI batch cap ${defaultBatch})`);
  }

  return rows;
}
